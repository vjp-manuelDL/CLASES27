    private void btnregistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnregistrarActionPerformed
       boolean registrado = false;
       
        // 1. Comprobar que el usuario no esté vacío
        String usuario = textusuario.getText().trim();
        if (usuario.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "El campo de usuario no puede estar vacío.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return; // Detiene el método aquí mismo
        }

        // 2. Comprobar que la contraseña tenga al menos 6 caracteres
        String password = new String(pwsr.getPassword());
        if (password.length() < 6) {
            javax.swing.JOptionPane.showMessageDialog(this, "La contraseña debe tener al menos 6 caracteres.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 3. Comprobar que las contraseñas coincidan
        String repetirPassword = new String(repetir.getPassword());
        if (!password.equals(repetirPassword)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Las contraseñas no coinciden.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 4. Comprobar que la casilla de condiciones esté marcada
        if (!condiciones.isSelected()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Debes aceptar las condiciones para registrarte.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // 5. Si el código llega hasta esta línea, significa que no ha fallado ningun campo
        registrado = true;
        
        String cursoSeleccionado = (String) cmbbox.getSelectedItem();
        javax.swing.JOptionPane.showMessageDialog(this, "Bienvenido, " + usuario + " (" + cursoSeleccionado + ")", "Información", javax.swing.JOptionPane.INFORMATION_MESSAGE);
        
    }//GEN-LAST:event_btnregistrarActionPerformed

