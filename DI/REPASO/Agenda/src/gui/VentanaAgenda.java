    private void btonanadirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btonanadirActionPerformed
        if (checktelefonoYnombre() == true) {
            String nombre = txtnombre.getText().trim();
            String tlf = tlflabel.getText().trim();

            DefaultTableModel modelo = (DefaultTableModel) jTable1.getModel();

            modelo.addRow(new Object[]{nombre, tlf});

            jLabel1.setText("Contactos : " + contador++);

        }
    }//GEN-LAST:event_btonanadirActionPerformed

    private void btoneliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btoneliminarActionPerformed
        int fila = jTable1.getSelectedRow();

        if (fila == -1) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error el contacto debe estar seleccionado",
                    "Error", javax.swing.JOptionPane.WARNING_MESSAGE);
        } else {
            int confirmacion = javax.swing.JOptionPane.showConfirmDialog(this,
                    "¿Estas seguro de que deseas eliminar este contacto?",
                    "Confirmar eliminacion",
                    javax.swing.JOptionPane.YES_NO_OPTION);
            // 4. Si el usuario pulsa "Sí" (YES_OPTION)
            if (confirmacion == javax.swing.JOptionPane.YES_OPTION) {
                // Recuperamos el modelo de tu tabla
                javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) jTable1.getModel();

                // Borramos la fila
                modelo.removeRow(fila);

                // Actualizamos el contador de contactos
                jLabel1.setText("Contactos: " + modelo.getRowCount());
            }

        }

    }//GEN-LAST:event_btoneliminarActionPerformed

    private boolean checktelefonoYnombre() {
        String nombre = txtnombre.getText().trim();
        String tlf = tlflabel.getText().trim();

        if (nombre.isEmpty() || nombre.equalsIgnoreCase("nombre")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error nombre debe estar relleno", "Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }
        if (!tlf.matches("\\d{9}") || tlf.equalsIgnoreCase("telefono")) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error telefono debe estar relleno con 9 digitos", "Error", javax.swing.JOptionPane.WARNING_MESSAGE);
            return false;
        }
        return true;
    }

