    private void btnAtacarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAtacarActionPerformed
        // TURNO 1: Héroe
        String turnoHeroe = heroe.ataca(jefe);
        txtLog.append(turnoHeroe + "\n");

        if (!jefe.vivo()) {
            txtLog.append("\n¡VICTORIA! Has derrotado a " + jefe.getNombre() + ".\n");
            btnAtacar.setEnabled(false);
            actualizarEstadisticas();
            return;
        }

        // TURNO 2: Jefe
        String turnoJefe = jefe.ataca(heroe);
        txtLog.append(turnoJefe + "\n\n");

        if (!heroe.vivo()) {
            txtLog.append("\n¡DERROTA! " + heroe.getNombre() + " ha caído.\n");
            btnAtacar.setEnabled(false);
        }

        actualizarEstadisticas();
    }//GEN-LAST:event_btnAtacarActionPerformed

