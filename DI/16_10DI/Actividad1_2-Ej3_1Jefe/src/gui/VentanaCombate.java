    // 3. MÉTODOS DE LÓGICA Y ACTUALIZACIÓN VISUAL
    private void cargarImagenes() {
// --- TAMAÑO DESEADO PARA LAS IMÁGENES ---
        int ancho = 250;
        int alto = 250;
        
        String rutaHeroe = "";
        if (heroe instanceof Guerrero) rutaHeroe = "/imagenes/guerrero.png";
        else if (heroe instanceof Mago) rutaHeroe = "/imagenes/mago.png";
        else if (heroe instanceof Arquero) rutaHeroe = "/imagenes/arquero.png";

        java.net.URL urlHeroe = getClass().getResource(rutaHeroe);
        if (urlHeroe != null) {
            // Cargar la imagen original
            javax.swing.ImageIcon iconoOriginal = new javax.swing.ImageIcon(urlHeroe);
            // Redimensionarla
            java.awt.Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(ancho, alto, java.awt.Image.SCALE_SMOOTH);
            // Aplicarla al JLabel
            lblImagenHeroe.setIcon(new javax.swing.ImageIcon(imagenEscalada));
        }

        java.net.URL urlJefe = getClass().getResource("/imagenes/jefe.png");
        if (urlJefe != null) {
            // Cargar la imagen original
            javax.swing.ImageIcon iconoOriginal = new javax.swing.ImageIcon(urlJefe);
            // Redimensionarla
            java.awt.Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(ancho, alto, java.awt.Image.SCALE_SMOOTH);
            // Aplicarla al JLabel
            lblImagenJefe.setIcon(new javax.swing.ImageIcon(imagenEscalada));
        }
    }

    private void actualizarEstadisticas() {
        lblHeroeInfo.setText(heroe.getNombre() + " (F: " + heroe.getFuerza() + " | D: " + heroe.getDefensa() + ")");
        lblVidaHeroe.setText("Vida: " + heroe.getVida() + " HP");

        lblJefeInfo.setText("Jefe " + jefe.getNombre() + " (F: " + jefe.getFuerza() + " | D: " + jefe.getDefensa() + ")");
        lblVidaJefe.setText("Vida: " + jefe.getVida() + " HP");
    }
