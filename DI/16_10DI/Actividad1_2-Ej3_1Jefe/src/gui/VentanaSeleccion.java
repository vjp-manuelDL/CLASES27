    private void btnJugarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnJugarActionPerformed
String nombre = txtNombre.getText().trim();
        if (nombre.isEmpty()) {
            nombre = "Héroe Desconocido";
        }

        String claseElegida = (String) cmbClase.getSelectedItem();
        
        // Polimorfismo: se asigna la subclase según la opción
        Personaje heroe;

        switch (claseElegida) {
            case "Mago":
                heroe = new Mago(nombre);
                break;
            case "Arquero":
                heroe = new Arquero(nombre);
                break;
            case "Guerrero":
            default:
                heroe = new Guerrero(nombre);
                break;
    }                                        
    // Abre VentanaCombate pasándole la variable heroe por parámetro y cierra la actual
        new VentanaCombate(heroe).setVisible(true);
        this.dispose();
    }//GEN-LAST:event_btnJugarActionPerformed


    
    
