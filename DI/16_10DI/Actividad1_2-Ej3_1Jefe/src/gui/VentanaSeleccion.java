    private void actualizarImagen() {
// --- TAMAÑO DESEADO PARA LA IMAGEN ---
        int ancho = 250;
        int alto = 250;
        
        String claseElegida = (String) cmbClase.getSelectedItem();
        String rutaImagen = "";

        if (claseElegida != null) {
            switch (claseElegida) {
                case "Guerrero":
                    rutaImagen = "/imagenes/guerrero.png";
                    break;
                case "Mago":
                    rutaImagen = "/imagenes/mago.png";
                    break;
                case "Arquero":
                    rutaImagen = "/imagenes/arquero.png";
                    break;
            }

            java.net.URL url = getClass().getResource(rutaImagen);
            if (url != null) {
                // Cargar la imagen original
                javax.swing.ImageIcon iconoOriginal = new javax.swing.ImageIcon(url);
                // Redimensionarla
                java.awt.Image imagenEscalada = iconoOriginal.getImage().getScaledInstance(ancho, alto, java.awt.Image.SCALE_SMOOTH);
                // Aplicarla al JLabel
                lblImagen.setIcon(new javax.swing.ImageIcon(imagenEscalada));
            } else {
                lblImagen.setIcon(null);
            }
        }
    }
