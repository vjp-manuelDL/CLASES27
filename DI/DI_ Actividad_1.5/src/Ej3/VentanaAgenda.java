    private void GUARDARActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_GUARDARActionPerformed
        // 1. Rescatar los textos de los JTextFields de tu jDialog1
    String nombre = lblname.getText();
    String telefono = lbltlf.getText();
    
    // Opcional: Comprobar que no estén vacíos
    if (!nombre.trim().isEmpty() && !telefono.trim().isEmpty()) {
        
        // 2. Crear el objeto Contacto
        Contacto nuevoContacto = new Contacto(nombre, telefono);
        
        // 3. Llamar al método del JFrame para procesar el contacto
        // (Este método debe estar creado en tu VentanaAgenda según el enunciado)
        this.recibirContacto(nuevoContacto);
        
        // 4. Limpiar los campos para la próxima vez
        lblname.setText("");
        lbltlf.setText("");
        
        // 5. Ocultar el diálogo (jDialog1)
        jDialog1.setVisible(false);
        
    } else {
        javax.swing.JOptionPane.showMessageDialog(this, "Rellena todos los campos", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
    }//GEN-LAST:event_GUARDARActionPerformed
    }
