    // Método para abrir el diálogo al pulsar "Reclutar"
    private void abrirDialogo() {
        txtnombre.setText(""); // Limpiar el área de texto
        jDialog1.setSize(800, 800);

        spinnermisiones.setValue(0); // Reiniciar el spinner
        jDialog1.setVisible(true); // Mostrar el diálogo modal
    }

    // Método para guardar los datos al pulsar "Guardar" dentro del diálogo
    private void guardarDatos() {
        String nombre = txtnombre.getText().trim();
        int misiones = (int) spinnermisiones.getValue();

        // Validación básica
        if (nombre.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(jDialog1, "El nombre no puede estar vacío.", "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
            return;
        }

        // Crear el objeto Astronauta
        Astronauta nuevoAstronauta = new Astronauta(nombre, misiones);

        // Añadirlo al modelo (esto actualizará la tabla automáticamente)
        modelo.addAstronauta(nuevoAstronauta);

        // Cerrar el diálogo
        jDialog1.dispose();
    }

