    private void btnSumarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSumarActionPerformed
        // 1. Obtener los textos de los campos
    String texto1 = txtNum1.getText().trim();
    String texto2 = txtNum2.getText().trim();
    
    // 2. CUIDADO CON: El usuario escribe letras y no números.
    // Usamos un try-catch para evitar que el programa se rompa.
    try {
        // Convertimos los textos a números enteros
        int num1 = Integer.parseInt(texto1);
        int num2 = Integer.parseInt(texto2);
        
        // Sumamos y mostramos el resultado
        int suma = num1 + num2;
        lblResultado.setText("Resultado: " + suma);
        
    } catch (NumberFormatException e) {
        // Si el usuario escribió letras, saltará este mensaje de error
        lblResultado.setText("Error: Por favor, introduce solo números.");
    }
    }//GEN-LAST:event_btnSumarActionPerformed

