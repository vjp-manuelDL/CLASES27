    private void btnRegistrarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnRegistrarActionPerformed
        String titulo = txtTitulo.getText().trim();
    String paginasTexto = txtPaginas.getText().trim();

    // 1. Validar que el título no esté vacío
    if (titulo.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, introduce el título del libro.", "Campo vacío", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    // 2. Validar que las páginas sean un número entero positivo
    try {
        int numPaginas = Integer.parseInt(paginasTexto);
        if (numPaginas <= 0) {
            javax.swing.JOptionPane.showMessageDialog(this, "El número de páginas debe ser mayor a 0.", "Valor incorrecto", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        boolean almacenado = chkAlmacenado.isSelected();

        // 3. Instanciar el objeto de la clase Libro (de la capa lógica)
        logica.Libro libro = new logica.Libro(numPaginas, titulo, almacenado);

        // 4. Mostrar el texto de resultado en la etiqueta
        lblResultado.setText(libro.obtenerTextoResultado());

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debes ingresar un número entero válido en las páginas.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnRegistrarActionPerformed

