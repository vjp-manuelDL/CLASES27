    private void ejecutarAtaque(logica.Personaje atacante, logica.Personaje defensor) {
        String resultadoAtaque = atacante.ataca(defensor);
        txtLog.append(resultadoAtaque + "\n");

        actualizarEstadisticas();

        if (!defensor.vivo()) {
            txtLog.append("\n¡" + defensor.getNombre() + " ha caído en combate!\n");
            txtLog.append("¡VICTORIA PARA " + atacante.getNombre().toUpperCase() + "!\n");

            btnAtacaP1.setEnabled(false);
            btnAtacaP2.setEnabled(false);

            btnEmpezar.setEnabled(true);
            txtP1.setEnabled(true);
            txtP2.setEnabled(true);
        }
    }

    private void actualizarEstadisticas() {
        lblStatsP1.setText("F: " + p1.getFuerza());
        lblStatsP2.setText("F: " + p2.getFuerza());
        lblStatsP3.setText("D: " + p1.getDefensa());
        lblStatsP4.setText("D: " + p2.getDefensa());
        lblStatsP5.setText("Vida: " + p1.getVida());
        lblStatsP6.setText("Vida: " + p2.getVida());
        
    }
    
   

