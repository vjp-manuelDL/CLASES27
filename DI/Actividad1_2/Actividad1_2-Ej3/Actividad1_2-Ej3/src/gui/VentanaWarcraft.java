    private void btnEmpezarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEmpezarActionPerformed
        String nombre1 = txtP1.getText().trim();
        String nombre2 = txtP2.getText().trim();

        // 1. Validar que ambos personajes tengan un nombre
        if (nombre1.isEmpty() || nombre2.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Ambos personajes deben tener un nombre.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 2. Validar que no tengan el mismo nombre
        if (nombre1.equalsIgnoreCase(nombre2)) {
            javax.swing.JOptionPane.showMessageDialog(this, "Los nombres de los personajes deben ser diferentes.", "Atención", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        // 3. Instanciar los dos objetos Personaje con estadísticas aleatorias
        p1 = new logica.Personaje(nombre1);
        p2 = new logica.Personaje(nombre2);

        // 4. Mostrar estadísticas iniciales en los JLabel
        actualizarEstadisticas();

        // 5. Iniciar el registro (log) y habilitar los botones de ataque
        txtLog.setText("--- ¡COMIENZA EL COMBATE! ---\n");
        btnAtacaP1.setText("Ataca " + p1.getNombre());
        btnAtacaP2.setText("Ataca " + p2.getNombre());

        btnAtacaP1.setEnabled(true);
        btnAtacaP2.setEnabled(true);

        // Mejora UX Extra: Bloquear los nombres y el botón de empezar durante el juego
        txtP1.setEnabled(false);
        txtP2.setEnabled(false);
        btnEmpezar.setEnabled(false);
    }//GEN-LAST:event_btnEmpezarActionPerformed

