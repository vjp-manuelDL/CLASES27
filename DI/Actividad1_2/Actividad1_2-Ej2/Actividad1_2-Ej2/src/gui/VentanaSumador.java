    private void btnSumarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSumarActionPerformed
        // Capturar el texto de los campos y quitar espacios sobrantes
    String texto1 = txtNum1.getText().trim();
    String texto2 = txtNum2.getText().trim();

    // Validar que no estén vacíos
    if (texto1.isEmpty() || texto2.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor, rellenar ambos campos numéricos.", "Campos vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        // Capturar textos y pasarlos a enteros
        int num1 = Integer.parseInt(texto1);
        int num2 = Integer.parseInt(texto2);

        // Instanciar el objeto SumadorPares pasándole los números
        logica.SumadorPares sumador = new logica.SumadorPares(num1, num2);

        // Llamar al método sumar() y mostrar el resultado en pantalla
        int resultado = sumador.sumar();
        lblResultado.setText("Resultado: " + resultado);

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Debes ingresar únicamente números enteros válidos.", "Error de formato", javax.swing.JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnSumarActionPerformed

