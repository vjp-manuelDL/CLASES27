    private void guardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_guardarActionPerformed
        String nom = nombre.getText().trim();
        if (nom.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Nombre del producto OBLIGATORIO", "ERROR", JOptionPane.ERROR_MESSAGE);
            return;
        }
        int cant = (Integer) cantidad.getValue();

        String cate = "";
        if (Alimentacion.isSelected()) {
            cate = "Alimentacion";
        } else if (Limpieza.isSelected()) {
            cate = "Limpieza";
        } else if (Electronica.isSelected()) {
            cate = "Eectronica";
        }

        Producto p = new Producto(nom, cant, cate);
        // 5. Mostrar los datos por consola
        System.out.println("--- PRODUCTO GUARDADO ---");
        System.out.println("Nombre: " + p.getNombre());
        System.out.println("Cantidad: " + p.getCandidad());
        System.out.println("Categoría: " + p.getCategoria());
    }//GEN-LAST:event_guardarActionPerformed

