public class Main {

    public static void main(String[] args) {

        int num1 = 10;
        int num2 = 1;

        System.out.println("El numero 1 es: " + num1);
        System.out.println("El numero 2 es: " + num2);

        System.out.println("La suma de los 2 numeros");
        int num3 = num1 + num2;
        System.out.println(num3);

        System.out.println("La resta de los 2 numeros");
        int num4 = num1 - num2;
        System.out.println(num4);

        System.out.println("La multiplicacion de los 2 numeros");
        int num5 = num1 * num2;
        System.out.println(num5);

        System.out.println("El módulo de los 2 numeros");
        int num6 = num1 % num2;
        System.out.println(num6);


    }
}